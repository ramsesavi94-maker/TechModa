const DICTIONARIES: Record<Lang, Dictionary> = { es, en, zh, ja };

export type Translate = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let text = DICTIONARIES[lang][key] ?? es[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
  }
  return text;
}

const STORAGE_KEY = 'techmoda.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && saved in DICTIONARIES) return saved;
  } catch {
    // sin almacenamiento
  }
  return 'es';
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

// Sin proveedor (p. ej. en pruebas) se usa español.
const I18nContext = createContext<I18nValue>({
  lang: 'es',
  setLang: () => {},
  t: (key, vars) => translate('es', key, vars),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // sin almacenamiento
    }
  }, []);

  const value = useMemo<I18nValue>(
    () => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
